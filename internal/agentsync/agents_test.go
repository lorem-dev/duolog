func TestPerAgentOverride(t *testing.T) {
	opts := testOpts(t)
	opts.Config.Overrides = map[string]config.Target{"architect": {Model: "terra", Effort: "medium"}}
	src := string(claudeSrc("architect", "model: opus\n", "x\n"))
	a := toCodex(t, src, opts)
	if a.Model != "gpt-6.1-terra" || a.Effort != "medium" {
		t.Fatalf("override: %#v", a)
	}
	opts.Flags = map[string]string{"opus": "luna"}
	a = toCodex(t, src, opts)
	if a.Model != "gpt-6-luna" {
		t.Fatalf("flag must win: %#v", a)
	}
	other := toCodex(t, strings.Replace(src, "architect", "other", 1), opts)
	if other.Model != "gpt-6-luna" {
		t.Fatalf("override leaked: %#v", other)
	}
}

