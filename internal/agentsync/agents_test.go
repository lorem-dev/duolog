// readBack decodes rendered TOML with an independent parser call.
func readBack(t *testing.T, data []byte) map[string]any {
	t.Helper()
	var m map[string]any
	if err := toml.Unmarshal(data, &m); err != nil {
		t.Fatalf("invalid TOML: %v\n%s", err, data)
	}
	return m
}

func TestEmojiInDescription(t *testing.T) {
	a := Agent{Name: "a", Description: "Ships \U0001F680 fast", Model: "gpt-6-sol", Body: "hi \U0001F600\n"}
	out, err := RenderCodexAgent(a)
	if err != nil {
		t.Fatal(err)
	}
	m := readBack(t, out)
	if m["description"] != a.Description || m["developer_instructions"] != a.Body {
		t.Fatalf("got %#v", m)
	}
}

func TestBodyEndingInTripleQuote(t *testing.T) {
	for _, body := range []string{"say \"\"\"", "say \"\"\"\n", "\"", "\"\"", "a\\\nb\\", "\n\nx"} {
		a := Agent{Name: "a", Description: "d", Body: body}
		out, err := RenderCodexAgent(a)
		if err != nil {
			t.Fatalf("%q: %v", body, err)
		}
		if got := readBack(t, out)["developer_instructions"]; got != body {
			t.Fatalf("%q: got %q\n%s", body, got, out)
		}
	}
}

func TestTrailingSpacesKept(t *testing.T) {
	a := Agent{Name: "a", Description: "d", Body: "one  \ntwo \t\nthree"}
	out, err := RenderCodexAgent(a)
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range strings.Split(string(out), "\n") {
		if strings.TrimRight(line, " \t") != line {
			t.Fatalf("trailing whitespace in %q", line)
		}
	}
	if got := readBack(t, out)["developer_instructions"]; got != a.Body {
		t.Fatalf("got %q", got)
	}
	md, err := RenderClaudeAgent(a)
	if err != nil {
		t.Fatal(err)
	}
	back, err := ParseClaudeAgent("a.md", md, testOpts(t))
	if err != nil {
		t.Fatal(err)
	}
	if back.Body != a.Body {
		t.Fatalf("body %q", back.Body)
	}
}

