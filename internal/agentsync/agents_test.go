func fixtureList(t *testing.T) []models.Entry {
	t.Helper()
	data, err := os.ReadFile("../../scripts/bench/fixtures/models/codex-debug-models.trimmed.json")
	if err != nil {
		t.Fatal(err)
	}
	var catalog struct {
		Models []models.Entry `json:"models"`
	}
	if err := json.Unmarshal(data, &catalog); err != nil {
		t.Fatal(err)
	}
	return catalog.Models
}

func testOpts(t *testing.T) AgentOpts {
	list := fixtureList(t)
	return AgentOpts{
		Config: config.AgentSync{
			ModelMap:      map[string]string{"fable": "astra", "opus": "sol", "sonnet": "terra", "haiku": "luna"},
			DefaultEffort: map[string]string{"fable": "high", "opus": "high", "sonnet": "medium", "haiku": "low"},
			EffortMap:     map[string]string{"low": "low", "medium": "medium", "high": "high", "xhigh": "xhigh", "max": "max", "ultra": "max"},
			CodexName:     "keep",
			DropKeys:      []string{"color"},
		},
		Resolve: func(alias string) (string, error) {
			name, ok := models.Latest(alias, list)
			if !ok {
				return "", os.ErrNotExist
			}
			return name, nil
		},
	}
}

func claudeSrc(name, extra, body string) []byte {
	return []byte("---\nname: " + name + "\ndescription: Does a job.\n" + extra + "---\n" + body)
}

func toCodex(t *testing.T, src string, opts AgentOpts) Agent {
	t.Helper()
	a, err := ParseClaudeAgent("a.md", []byte(src), opts)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

func TestRoundTripClaudeCodexClaude(t *testing.T) {
	opts := testOpts(t)
	src, err := os.ReadFile("testdata/architect.md")
	if err != nil {
		t.Fatal(err)
	}
	codex, err := ParseClaudeAgent("architect.md", src, opts)
	if err != nil {
		t.Fatal(err)
	}
	file, err := RenderCodexAgent(codex)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(file), "# Generated by duolog sync. Do not edit.\n") {
		t.Fatalf("missing generated comment:\n%s", file)
	}
	claude, err := ParseCodexAgent("architect.toml", file, opts)
	if err != nil {
		t.Fatal(err)
	}
	want := Agent{
		Name:        "architect",
		Description: "Designs the structure of a change before code is written.",
		Model:       "opus",
		Effort:      "high",
		Body:        "You are the architect.\n\nKeep answers short.  \nSecond line after a hard break.\n",
	}
	if claude != want {
		t.Fatalf("got %#v want %#v", claude, want)
	}
	out, err := RenderClaudeAgent(claude)
	if err != nil {
		t.Fatal(err)
	}
	again, err := ParseClaudeAgent("out.md", out, opts)
	if err != nil {
		t.Fatal(err)
	}
	if again != codex {
		t.Fatalf("got %#v want %#v", again, codex)
	}
}

