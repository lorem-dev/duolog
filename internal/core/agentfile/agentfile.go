// Package agentfile holds what the sync of agent files shares between the
// agents' formats: the neutral agent, the options of one conversion, the port
// that each agent implements, and the mapping of models and efforts.
package agentfile

import "github.com/lorem-dev/duolog/internal/core/config"

// GeneratedComment opens every file that sync generates.
const GeneratedComment = "# Generated by duolog sync. Do not edit."

// Agent is an agent file in the form of the file that will be written.
// ParseAgent of one format returns it in the form of the target format.
type Agent struct {
	Name        string
	Description string
	Model       string
	Effort      string
	Body        string
	// Original is the name as the source file spells it, before a rename for
	// the target. Resolved is the concrete model written for the target when
	// the source format resolved an alias; it is empty when it did not. Neither
	// is part of the written file.
	Original string
	Resolved string
}

// Content returns a with the fields that are not part of the written file
// cleared, so that an agent read back from a file compares equal to it.
func (a Agent) Content() Agent {
	a.Original, a.Resolved = "", ""
	return a
}

// AgentOpts holds the settings for one conversion.
type AgentOpts struct {
	Config config.AgentSync
	// To names the agent whose file the conversion produces.
	To string
	// Flags maps a source alias to a target alias, from --model opus=terra.
	Flags map[string]string
	// Resolve turns a Codex alias into the concrete model written to the file.
	Resolve func(alias string) (string, error)
}

// Dirs names where an agent keeps its files, relative to the project root, and
// the extension of an agent file.
type Dirs struct {
	Agents, Skills, Ext string
}

// Format is what sync needs of one agent: its folders, its agent files and its
// skills. A source format parses into the neutral Agent for a target agent, and
// the target format renders it.
type Format interface {
	Dirs() Dirs
	// ParseAgent reads an agent file of this format and returns it in the form
	// of the file that the agent o.To keeps.
	ParseAgent(path string, src []byte, o AgentOpts) (Agent, error)
	// RenderAgent writes an agent file of this format and reads it back to check it.
	RenderAgent(a Agent) ([]byte, error)
	// Skill rewrites the frontmatter of a SKILL.md for the other agent, drops
	// the keys in drop, and returns the warnings for what the other agent
	// does not honour.
	Skill(src []byte, drop []string) ([]byte, []string, error)
	// Check reports whether data parses as an agent file of this format.
	Check(path string, data []byte) error
}
