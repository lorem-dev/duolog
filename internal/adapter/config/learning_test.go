func keysOf(entries []config.LadderEntry) []string {
	var keys []string
	for _, e := range entries {
		keys = append(keys, e.Key())
	}
	return keys
}

func TestRenderLearnedRouting(t *testing.T) {
	st := map[string]config.EntryStat{"codex/sol/medium": {Delegations: 4, Weight: 2.5, Quality: 2.8, USD: 0.31, Seconds: 95}}
	b, err := RenderLearnedRouting(config.LearnedRouting{Ladders: map[string]config.LearnedLadder{"debug": {Order: []string{"codex/sol/medium"}, Stats: st}}})
	if err != nil || !strings.HasPrefix(string(b), "# Generated by duolog learn --apply. Delete this file to return to the configured ladders.\nladders:\n  debug:\n    order:\n") {
		t.Fatal(string(b), err)
	}
}

func loadWithProject(t *testing.T, project string) (*config.Config, string, error) {
	t.Helper()
	root := isolatedRoot(t)
	if project != "" {
		writeConfig(t, filepath.Join(root, ".duolog", "config.yaml"), project)
	}
	cfg, err := Load(root)
	return cfg, root, err
}

func TestLearningDefaultsLoad(t *testing.T) {
	cfg, err := Load(isolatedRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	l := cfg.Learning
	if l.Enabled || l.Threshold != 2.5 || l.QualityMargin != 0.25 || l.PriorRuns != 2 || l.Uncertainty != 0.5 || l.ProfileBelowRuns != 3 {
		t.Fatalf("unexpected defaults: %+v", l)
	}
	for _, name := range []string{"skeleton", "plan_review", "debug_multi", "feature", "implement", "debug", "tests", "review", "mechanical", "docs"} {
		if _, ok := l.Classes[name]; !ok {
			t.Errorf("class %s missing", name)
		}
	}
	if got := keysOf(l.Classes["debug"].Ladder); !slices.Equal(got, []string{"codex/terra/medium", "codex/sol/medium", "claude/opus/high"}) {
		t.Fatalf("debug ladder: %v", got)
	}
	if got := l.Classes["skeleton"].Steps["plan"][0].Key(); got != "claude/opus/high" {
		t.Fatalf("skeleton plan first: %s", got)
	}
	for name, c := range l.Classes {
		all := append([]config.LadderEntry{}, c.Ladder...)
		for _, s := range c.Steps {
			all = append(all, s...)
		}
		for _, e := range all {
			if e.Effort != "low" && e.Effort != "medium" && e.Effort != "high" {
				t.Errorf("%s: effort %s above high", name, e.Effort)
			}
		}
	}
}

