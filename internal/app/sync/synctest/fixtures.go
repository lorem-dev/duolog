package synctest

import (
	"github.com/lorem-dev/duolog/internal/core/agentfile"
	"github.com/lorem-dev/duolog/internal/core/config"
)

// agentSync is the sync configuration that the fixtures convert with.
func agentSync() config.AgentSync {
	return config.AgentSync{
		ModelMap:      map[string]string{"fable": "astra", "opus": "sol", "sonnet": "terra", "haiku": "luna"},
		DefaultEffort: map[string]string{"fable": "high", "opus": "high", "sonnet": "medium", "haiku": "low"},
		EffortMap:     map[string]string{"low": "low", "medium": "medium", "high": "high", "xhigh": "xhigh", "max": "max", "ultra": "max"},
		CodexName:     "keep",
		DropKeys:      []string{"color"},
	}
}

func resolve(alias string) (string, error) { return "gpt-6.1-" + alias, nil }

const skillSrc = "---\nname: lint\ndescription: Lints.\ndisable-model-invocation: true\nextra: x\n---\nBody stays.\n"

const skillOut = "---\n# Generated by duolog sync. Do not edit.\nname: lint\ndescription: Lints.\ndisable-model-invocation: true\n---\nBody stays.\n"

// ClaudeFixture is the data for Claude's format.
func ClaudeFixture() Fixture {
	return Fixture{
		To:      "codex",
		Config:  agentSync(),
		Resolve: resolve,
		Source:  []byte("---\nname: architect\ndescription: Designs a change.\nmodel: opus\neffort: high\ncolor: blue\n---\nYou are the architect.\n"),
		Parsed: agentfile.Agent{Name: "architect", Description: "Designs a change.", Model: "gpt-6.1-sol", Effort: "high",
			Body: "You are the architect.\n", Original: "architect", Resolved: "gpt-6.1-sol"},
		Agent:         agentfile.Agent{Name: "architect", Description: "Designs a change.", Model: "opus", Effort: "high", Body: "You are the architect.\n"},
		Rendered:      []byte("---\n# Generated by duolog sync. Do not edit.\nname: architect\ndescription: Designs a change.\nmodel: opus\neffort: high\n---\nYou are the architect.\n"),
		SkillSrc:      []byte(skillSrc),
		SkillOut:      []byte(skillOut),
		Drop:          []string{"extra"},
		SkillWarnings: []string{"disable-model-invocation is not honoured by Codex; the model may still pick this skill"},
	}
}

