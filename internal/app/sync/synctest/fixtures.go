// NewFake returns a Fake scripted to pass FormatContract with fx.
func NewFake(fx Fixture) *Fake {
	return &Fake{
		Folders:       agentfile.Dirs{Agents: ".fake/agents", Skills: ".fake/skills", Ext: ".fake"},
		Parsed:        fx.Parsed,
		Rendered:      fx.Rendered,
		SkillOut:      fx.SkillOut,
		SkillWarnings: fx.SkillWarnings,
		Valid:         fx.Rendered,
	}
}
